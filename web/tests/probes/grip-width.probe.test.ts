/**
 * Stage 0, measurement 1: **the widest thing the gripper actually holds through a lift and a
 * move.**
 *
 * Every size in the workbench's list of things is provisional until this lands
 * (`workbench-requirements.md` 5). The plan guessed from the demo in hand - "the current demo
 * grips 30 mm blocks, so 32 mm is the working ceiling" - which is not a measurement: 30 mm is
 * the only width that demo has ever been asked for.
 *
 * So: a scene with one free box, 30 mm deep and 30 mm tall and **W wide across the jaws**, and
 * for each W the whole job the demo does - come down on it with the jaws open, close them,
 * take it with the weld, lift it, carry it across the bench, put it down, let go. The width
 * passes when the jaws closed on **both** sides, the box was not shoved aside on the way, and
 * it ends up where it was being put, flat and still on the bench.
 *
 * Three things could stop a wide box, and the report says which one did:
 *
 * - **the jaws will not open round it** - the gap at the gripper's own limit;
 * - **the jaws do not both touch it** - one pad on it and one off, which is a push, not a grip;
 * - **it does not arrive** - shoved out of the jaws, or dropped on the way.
 *
 * Where the box sits between the jaws is not guessed either. The fixed jaw does not move, so a
 * box's face has to be put against it: a 30 mm block is gripped with its centre 3.1 mm to the
 * +open side of the gripper site (`GRIP_OFFSET` in `src/sim/arm.ts`, measured by
 * `grip.probe.test.ts`), which puts that unmoving face at 3.1 - 15 = **-11.9 mm**. Everything
 * wider is centred from there, and two nearby aims are tried as well, so a width is never
 * failed for being badly aimed.
 *
 * Run: `PROBES=1 npx vitest run tests/probes/grip-width.probe.test.ts`
 * Report: `out/stage0-grip-width.txt`
 */

